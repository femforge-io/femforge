_HEX_PREFIX = re.compile(r"[0-9a-f]{18}")


def bundle_name(cache_key: str) -> str:
    """The memorable, deterministic bundle-directory name for a content key: words picked by hash bits, suffixed with the key's leading 8 hex characters."""
    key = cache_key.lower()
    if not _HEX_PREFIX.match(key):
        raise ValueError(f"bundle_name expects a hex content key (>= 18 hex chars), got {cache_key!r}.")

    # 20-bit indices over 512-entry lists: 2^20 is a multiple of 512, so both draws are exactly uniform.
    # Chosen once, before any bundle existed; frozen with the lists.
    adjective = _ADJECTIVES[int(key[8:13], 16) % len(_ADJECTIVES)]
    noun = _NOUNS[int(key[13:18], 16) % len(_NOUNS)]
    return f"{adjective}-{noun}-{key[:8]}"
